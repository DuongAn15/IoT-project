-- P00: Supabase catalog audit — READ ONLY (SELECT statements only).
-- Run only against the intended project/environment after confirming the project ref.
-- Never paste API keys, JWTs, passwords, or connection strings into this file or its output.
-- `weather_logs` is the code default. If SUPABASE_TABLE differs, replace it below.
-- This file does not inspect or return telemetry/device row contents.

-- 1. Confirm the expected relations exist in public.
select requested.table_name,
       to_regclass(format('public.%I', requested.table_name)) as relation
from (values ('devices'), ('weather_logs')) as requested(table_name)
order by requested.table_name;

-- 2. Column names, types, nullability, defaults, and ordinal positions.
select table_name, ordinal_position, column_name, data_type, udt_name,
       is_nullable, column_default
from information_schema.columns
where table_schema = 'public'
  and table_name in ('devices', 'weather_logs')
order by table_name, ordinal_position;

-- 3. Primary keys, unique/check/foreign-key constraints and validation state.
select ns.nspname as schema_name,
       tbl.relname as table_name,
       con.conname as constraint_name,
       con.contype as constraint_type,
       con.convalidated as is_validated,
       pg_get_constraintdef(con.oid) as definition
from pg_constraint con
join pg_class tbl on tbl.oid = con.conrelid
join pg_namespace ns on ns.oid = tbl.relnamespace
where ns.nspname = 'public'
  and tbl.relname in ('devices', 'weather_logs')
order by tbl.relname, con.conname;

-- 4. All indexes, including indexes not backed by a named constraint.
select schemaname, tablename, indexname, indexdef
from pg_indexes
where schemaname = 'public'
  and tablename in ('devices', 'weather_logs')
order by tablename, indexname;

-- 5. RLS state and policies. Policy expressions can reveal access rules; review output before sharing.
select ns.nspname as schema_name,
       tbl.relname as table_name,
       tbl.relrowsecurity as rls_enabled,
       tbl.relforcerowsecurity as force_rls
from pg_class tbl
join pg_namespace ns on ns.oid = tbl.relnamespace
where ns.nspname = 'public'
  and tbl.relname in ('devices', 'weather_logs')
order by tbl.relname;

select schemaname, tablename, policyname, permissive, roles, cmd, qual, with_check
from pg_policies
where schemaname = 'public'
  and tablename in ('devices', 'weather_logs')
order by tablename, policyname;

-- 6. Table-level and column-level grants visible to the current audit role.
select table_schema, table_name, grantee, grantor, privilege_type, is_grantable
from information_schema.role_table_grants
where table_schema = 'public'
  and table_name in ('devices', 'weather_logs')
order by table_name, grantee, privilege_type;

select table_schema, table_name, column_name, grantee, privilege_type, is_grantable
from information_schema.column_privileges
where table_schema = 'public'
  and table_name in ('devices', 'weather_logs')
order by table_name, column_name, grantee, privilege_type;

-- 7. Approximate table statistics only; this does not scan or return table rows.
select schemaname, relname, n_live_tup, n_dead_tup, last_analyze, last_autoanalyze
from pg_stat_user_tables
where schemaname = 'public'
  and relname in ('devices', 'weather_logs')
order by relname;

-- Follow-up A (read only): determine whether weather_logs.id is generated by
-- an identity column or an associated serial/identity sequence. A trigger can
-- also populate an ID; this query does not inspect trigger behavior.
select c.table_schema,
       c.table_name,
       c.column_name,
       c.data_type,
       c.is_identity,
       c.identity_generation,
       c.column_default,
       pg_get_serial_sequence(format('%I.%I', c.table_schema, c.table_name), c.column_name) as owned_sequence
from information_schema.columns c
where c.table_schema = 'public'
  and c.table_name = 'weather_logs'
  and c.column_name = 'id';

-- Follow-up B (read only): compact summary of column-level ACLs, grouped by
-- role and privilege so the result is less likely to be truncated in SQL Editor.
select table_schema,
       table_name,
       grantee,
       privilege_type,
       is_grantable,
       count(*) as column_count,
       array_agg(column_name order by column_name) as columns
from information_schema.column_privileges
where table_schema = 'public'
  and table_name in ('devices', 'weather_logs')
group by table_schema, table_name, grantee, privilege_type, is_grantable
order by table_name, grantee, privilege_type;
