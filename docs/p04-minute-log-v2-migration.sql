-- P04 v2 Minute-Log Table & Idempotency Migration (Reviewable DDL; do not run on live without P04 cutover approval)
CREATE TABLE IF NOT EXISTS public.weather_logs_v2 (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id TEXT NOT NULL REFERENCES public.devices(device_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  deployment_id TEXT NOT NULL,
  boot_id TEXT NOT NULL,
  window_sequence INTEGER NOT NULL CHECK (window_sequence >= 1),
  payload_hash TEXT NOT NULL,
  clock_quality TEXT NOT NULL CHECK (clock_quality IN ('synchronized', 'unsynchronized')),
  recorded_at TIMESTAMPTZ NOT NULL,
  received_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  temperature DOUBLE PRECISION NOT NULL,
  humidity DOUBLE PRECISION NOT NULL,
  wind_speed DOUBLE PRECISION NOT NULL,
  rain_rate DOUBLE PRECISION NOT NULL,
  rainfall_mm DOUBLE PRECISION NOT NULL,
  CONSTRAINT weather_logs_v2_identity_unique UNIQUE (device_id, deployment_id, boot_id, window_sequence)
);

CREATE INDEX IF NOT EXISTS idx_weather_logs_v2_device_time
  ON public.weather_logs_v2 (device_id, recorded_at DESC);

ALTER TABLE public.weather_logs_v2 ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.weather_logs_v2 FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT ON TABLE public.weather_logs_v2 TO service_role;
